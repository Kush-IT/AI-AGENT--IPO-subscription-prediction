"""
State definitions and Pydantic schemas for the Agentic AI Orchestration Layer.
"""
from typing import Dict, List, Any, Optional, TypedDict
from pydantic import BaseModel, Field


class IPOInputSchema(BaseModel):
    """Raw input payload for an Indian Mainboard IPO to be analyzed."""
    company_name: str = Field(..., description="Company name seeking listing")
    ipo_open_date: str = Field(..., description="Subscription opening date in YYYY-MM-DD format")
    price_high: float = Field(..., description="Upper price band (Cap price in INR)")
    price_low: Optional[float] = Field(None, description="Lower price band (Floor price in INR)")
    issue_size_in_crore: float = Field(..., description="Total offering size in INR Crore")
    lot_size: Optional[int] = Field(None, description="Minimum bidding lot size")
    sector: Optional[str] = Field("Other", description="Business industry sector")
    
    # Optional financial & quota terms
    face_value: Optional[float] = Field(10.0, description="Share face value in INR")
    qib_quota_pct: Optional[float] = Field(50.0, description="QIB reservation percentage")
    nii_quota_pct: Optional[float] = Field(15.0, description="NII/HNI reservation percentage")
    retail_quota_pct: Optional[float] = Field(35.0, description="Retail reservation percentage")
    fresh_issue_percentage: Optional[float] = Field(50.0, description="Fresh issue percentage")
    ofs_percentage: Optional[float] = Field(50.0, description="Offer for Sale percentage")
    
    # Financial fundamentals
    revenue_latest_cr: Optional[float] = Field(500.0, description="Latest FY Restated Revenue (INR Cr)")
    pat_latest_cr: Optional[float] = Field(50.0, description="Latest FY Profit After Tax (INR Cr)")
    operating_cash_flow_cr: Optional[float] = Field(40.0, description="Latest FY Operating Cash Flow (INR Cr)")
    ebitda_margin_pct: Optional[float] = Field(15.0, description="Latest FY EBITDA Margin (%)")
    revenue_cagr_3yr: Optional[float] = Field(18.0, description="3-Year Revenue CAGR (%)")
    pat_cagr_3yr: Optional[float] = Field(20.0, description="3-Year PAT CAGR (%)")
    roe_pct: Optional[float] = Field(16.0, description="Return on Equity (%)")
    roce_pct: Optional[float] = Field(18.0, description="Return on Capital Employed (%)")
    debt_equity_ratio: Optional[float] = Field(0.5, description="Debt to Equity Ratio")
    eps_pre_ipo: Optional[float] = Field(12.0, description="Pre-IPO Earnings Per Share (INR)")
    pe_ratio: Optional[float] = Field(25.0, description="P/E Multiple based on upper price cap")
    industry_pe: Optional[float] = Field(30.0, description="Listed Peer Group Median P/E")
    pb_ratio: Optional[float] = Field(3.5, description="Price to Book Value")
    
    # Secondary market & sentiment
    nifty_1d_return: Optional[float] = Field(0.05, description="NIFTY 1-day percentage return prior to open")
    nifty_5d_return: Optional[float] = Field(0.35, description="NIFTY 5-day percentage return prior to open")
    nifty_20d_return: Optional[float] = Field(1.20, description="NIFTY 20-day percentage return prior to open")
    sensex_1d_return: Optional[float] = Field(0.05, description="SENSEX 1-day percentage return")
    sensex_5d_return: Optional[float] = Field(0.35, description="SENSEX 5-day percentage return")
    sensex_20d_return: Optional[float] = Field(1.20, description="SENSEX 20-day percentage return")
    india_vix: Optional[float] = Field(14.5, description="India VIX level prior to open")
    india_vix_5d_change: Optional[float] = Field(0.0, description="India VIX 5-day absolute change")
    market_trend: Optional[str] = Field("NEUTRAL", description="Market regime (BULLISH, BEARISH, NEUTRAL, VOLATILE)")
    
    # Media sentiment and unofficial GMP
    news_count: Optional[int] = Field(15, description="Pre-IPO media news article count")
    positive_news_ratio: Optional[float] = Field(0.65, description="Ratio of positive news coverage [0, 1]")
    negative_news_ratio: Optional[float] = Field(0.15, description="Ratio of negative news coverage [0, 1]")
    average_sentiment_score: Optional[float] = Field(0.50, description="Average FinBERT sentiment score [0, 1]")
    gmp_in_inr: Optional[float] = Field(None, description="Grey Market Premium in INR")
    gmp_percentage: Optional[float] = Field(None, description="Grey Market Premium percentage (%)")


class IPOAnalysisResponse(BaseModel):
    """Comprehensive structured response payload generated by Agentic AI."""
    status: str
    company_name: str
    ipo_open_date: str
    predictions: Dict[str, Any]
    category_assessment: Dict[str, Any]
    confidence: Dict[str, Any]
    top_positive_factors: List[Dict[str, Any]]
    top_negative_factors: List[Dict[str, Any]]
    grouped_driver_impacts: Dict[str, Any]
    risk_assessment: Dict[str, Any]
    data_quality: Dict[str, Any]
    temporal_validation: Dict[str, Any]
    model_information: Dict[str, Any]
    sources: List[Dict[str, Any]]
    feature_provenance: Dict[str, Any]
    disclaimer: str


class IPOState(TypedDict):
    """LangGraph internal state dict flowing across agent nodes."""
    ipo_input: Dict[str, Any]
    validated_data: Dict[str, Any]
    features: Dict[str, Any]
    feature_metadata: Dict[str, Any]
    feature_provenance: Dict[str, Any]
    temporal_rejections: List[Dict[str, Any]]
    data_quality: Dict[str, Any]
    predictions: Dict[str, Any]
    shap_explanations: Dict[str, Any]
    category_assessment: Dict[str, Any]
    risk_assessment: Dict[str, Any]
    confidence: Dict[str, Any]
    final_report: Dict[str, Any]
    errors: List[str]
    warnings: List[str]
    sources: List[Dict[str, Any]]
    status: str
